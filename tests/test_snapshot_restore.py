class SessionIdInference(unittest.TestCase):
    """Sessions that predate the tagging hook are matched by comparing the
    `claude` process start time to each transcript's first timestamp."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.cwd = "/srv/Sites"
        self.slug = snapshot.slug_for_cwd(self.cwd)
        os.makedirs(os.path.join(self.tmp.name, self.slug))
        self._orig = snapshot.PROJECTS_DIR
        snapshot.PROJECTS_DIR = self.tmp.name
        self.addCleanup(lambda: setattr(snapshot, "PROJECTS_DIR", self._orig))
        snapshot._slug_first_ts.clear()
        snapshot._claimed_ids.clear()
        snapshot._live_procs = None

    def write_transcript(self, sid, when):
        path = os.path.join(self.tmp.name, self.slug, f"{sid}.jsonl")
        with open(path, "w") as fh:
            fh.write(json.dumps({"type": "summary", "summary": "no timestamp"}) + "\n")
            fh.write(json.dumps({"type": "user", "timestamp": when.isoformat()}) + "\n")
        return path

    def set_procs(self, procs):
        snapshot._live_procs = procs

    def test_nearest_transcript_after_process_start_wins(self):
        start = datetime(2026, 9, 21, 12, 0, 0)
        self.write_transcript("early", start - timedelta(hours=3))
        self.write_transcript("match", start + timedelta(seconds=2))
        self.write_transcript("later", start + timedelta(hours=1))
        self.set_procs([("1", "ttys9", start.timestamp())])
        self.assertEqual(snapshot.infer_session_id("/dev/ttys9", self.cwd), "match")

    def test_two_sessions_in_one_directory_do_not_collide(self):
        a = datetime(2026, 9, 21, 9, 0, 0)
        b = datetime(2026, 9, 21, 11, 30, 0)
        self.write_transcript("sid-a", a + timedelta(seconds=1))
        self.write_transcript("sid-b", b + timedelta(seconds=1))
        self.set_procs([("1", "ttys1", a.timestamp()), ("2", "ttys2", b.timestamp())])
        self.assertEqual(snapshot.infer_session_id("/dev/ttys1", self.cwd), "sid-a")
        self.assertEqual(snapshot.infer_session_id("/dev/ttys2", self.cwd), "sid-b")

    def test_an_id_is_never_handed_out_twice(self):
        start = datetime(2026, 9, 21, 12, 0, 0)
        self.write_transcript("only", start + timedelta(seconds=1))
        self.set_procs([
            ("1", "ttys1", start.timestamp()),
            ("2", "ttys2", start.timestamp()),
        ])
        self.assertEqual(snapshot.infer_session_id("/dev/ttys1", self.cwd), "only")
        self.assertIsNone(snapshot.infer_session_id("/dev/ttys2", self.cwd))

    def test_transcript_long_before_the_process_is_not_a_match(self):
        start = datetime(2026, 9, 21, 12, 0, 0)
        self.write_transcript("stale", start - timedelta(days=2))
        self.set_procs([("1", "ttys9", start.timestamp())])
        self.assertIsNone(snapshot.infer_session_id("/dev/ttys9", self.cwd))

    def test_no_live_process_on_that_tty(self):
        self.set_procs([])
        self.assertIsNone(snapshot.infer_session_id("/dev/ttys9", self.cwd))

    def test_stale_tag_is_detected_by_its_missing_transcript(self):
        self.write_transcript("real", datetime(2026, 9, 21, 12, 0, 0))
        self.assertTrue(snapshot.transcript_exists("real", self.cwd))
        self.assertFalse(snapshot.transcript_exists("left-behind", self.cwd))


class PlannedStructure(unittest.TestCase):
    """Restore must rebuild what was captured, not regroup it by project."""

    CAPTURE = {
        "windows": [
            {
                "window_id": 1,
                "title": "One",
                "frame": {"x": 0, "y": 0, "w": 100, "h": 100},
                "space": 3,
                "tabs": [
                    {"index": 1, "title": "t1", "sessions": [
                        {"name": "a", "badge": "", "cwd": "/p/alpha",
                         "claude_session_id": "id-a", "mission": "do a"}]},
                    {"index": 2, "title": "t2", "sessions": [
                        {"name": "b", "badge": "", "cwd": "/p/beta",
                         "claude_session_id": "id-b", "mission": None}]},
                ],
            },
            {
                "window_id": 2,
                "title": "Two",
                "frame": {"x": 5, "y": 5, "w": 50, "h": 50},
                "space": -1,
                "tabs": [
                    {"index": 1, "title": "t1", "sessions": [
                        {"name": "c", "badge": "", "cwd": "/p/alpha",
                         "claude_session_id": None, "mission": None}]},
                ],
            },
        ]
    }

    def plan(self):
        return driver.build_plan(self.CAPTURE["windows"])

    def test_window_and_tab_counts_match_the_capture(self):
        lines = self.plan()
        self.assertEqual(sum(l.startswith("[window ") for l in lines), 2)
        self.assertEqual(sum(l.strip().startswith("[tab ") for l in lines), 3)

    def test_two_directories_in_one_window_are_not_split_apart(self):
        lines = self.plan()
        second = next(i for i, l in enumerate(lines) if l.startswith("[window 2]"))
        first_window = "\n".join(lines[:second])
        self.assertIn("/p/alpha", first_window)
        self.assertIn("/p/beta", first_window)

    def test_tabs_keep_their_captured_order(self):
        order = [l for l in self.plan() if l.strip().startswith("[tab ")]
        self.assertEqual(order[0].strip(), "[tab 1] title='t1'")
        self.assertEqual(order[1].strip(), "[tab 2] title='t2'")

    def test_known_space_is_applied_and_unknown_is_skipped(self):
        plan = "\n".join(self.plan())
        self.assertIn("spacesctl move <new-window-id> 3", plan)
        self.assertIn("space unknown", plan)

    def test_a_session_without_an_id_starts_fresh(self):
        plan = "\n".join(self.plan())
        self.assertIn("cmd='claude --resume id-a'", plan)
        self.assertIn("cmd='claude'", plan)


