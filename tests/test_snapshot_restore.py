"""Tests for the parts of capture and restore that don't need iTerm running.

A live restore opens a dozen windows on top of whatever you're doing, so it is
not something CI (or a working machine) can run. These cover the logic that
would otherwise only be exercised by that untestable path: shell quoting,
mission extraction, stale-tag rejection, session-id inference, and the
window/tab structure the driver plans from a capture.

    python3 tests/test_snapshot_restore.py
"""

import asyncio
import importlib.util
import json
import os
import sys
import tempfile
import unittest
from datetime import datetime, timedelta

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, os.path.join(REPO, path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# The driver reads sys.argv at import time; keep it out of restore mode.
_argv = sys.argv
sys.argv = ["claude-restore-driver.py", "--dry-run"]
driver = load("driver", "scripts/claude-restore-driver.py")
sys.argv = _argv

snapshot = load("snapshot", "scripts/claude-iterm-snapshot.py")


class ShellQuoting(unittest.TestCase):
    """A session named "Blocking Dana's iPhone hotspot" used to break the
    command line it was interpolated into, leaving the shell mid-quote."""

    def cmd(self, **over):
        sdef = {
            "name": "plain",
            "badge": "plain",
            "cwd": "/tmp/work",
            "claude_session_id": "abc-123",
        }
        sdef.update(over)
        return driver.build_cmd(sdef)

    def test_apostrophe_in_name_does_not_break_quoting(self):
        cmd = self.cmd(name="Blocking Dana's iPhone hotspot")
        self.assertNotIn("'Blocking Dana's", cmd)
        self.assertIn("iPhone hotspot", cmd)

    def test_apostrophe_in_badge_does_not_break_quoting(self):
        self.assertIn("base64", self.cmd(badge="Dana's"))

    def test_metacharacters_are_not_executed(self):
        for hostile in ("; rm -rf /tmp/x", "$(id)", "`id`", "a && b"):
            cmd = self.cmd(name=hostile)
            self.assertNotIn(f"; {hostile}", cmd)
            self.assertIn("claude --resume", cmd)

    def test_cwd_with_spaces_is_quoted(self):
        self.assertIn("'/tmp/my work'", self.cmd(cwd="/tmp/my work"))

    def test_resume_only_when_an_id_is_present(self):
        self.assertIn("claude --resume abc-123", self.cmd())
        self.assertTrue(self.cmd(claude_session_id=None).endswith("&& claude"))


